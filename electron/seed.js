function seedPrompts(d) {
  // 每次启动重置内置提示词为最新版本（内置不可编辑，用户自定义不受影响）
  d.prepare('DELETE FROM prompts WHERE builtin=1').run()
  const insert = d.prepare(
    'INSERT INTO prompts (novel_id, name, category, system_prompt, user_prompt, params, builtin) VALUES (NULL, ?, ?, ?, ?, ?, 1)'
  )
  const tx = d.transaction((list) => {
    for (const p of list) insert.run(p.name, p.category, p.system, p.user, JSON.stringify(p.params))
  })
  tx(BUILTIN_PROMPTS)
}

